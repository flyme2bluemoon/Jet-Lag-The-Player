import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(appDirectory, "assets", "geojson");
const outputDirectory = path.join(appDirectory, "public", "geojson", "generated");
const manifestPath = path.join(appDirectory, "src", "generated", "geojson-assets.ts");
const supportedExtensions = new Set([".geojson", ".json"]);

function getExportName(sourceName) {
    const sourceExtension = path.extname(sourceName);
    const extension = sourceExtension.toLowerCase();
    const basename = path.basename(sourceName, sourceExtension);
    const identifier = basename.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase();
    const suffix = extension === ".geojson" ? "_GEOJSON_URL" : "_URL";
    const exportName = `${identifier}${suffix}`;

    if (!/^[A-Z_][A-Z0-9_]*$/.test(exportName)) {
        throw new Error(`Cannot derive a valid TypeScript export from ${sourceName}`);
    }

    return exportName;
}

export async function generateGeoJsonAssets() {
    const sourceEntries = await readdir(sourceDirectory, { withFileTypes: true });
    const sourceNames = sourceEntries
        .filter((entry) => entry.isFile())
        .map((entry) => entry.name)
        .filter((sourceName) =>
            supportedExtensions.has(path.extname(sourceName).toLowerCase()),
        )
        .sort();

    if (sourceNames.length === 0) {
        throw new Error(`No GeoJSON assets found in ${sourceDirectory}`);
    }

    const assets = sourceNames.map((sourceName) => [
        getExportName(sourceName),
        sourceName,
    ]);
    const exportNames = new Set(assets.map(([exportName]) => exportName));

    if (exportNames.size !== assets.length) {
        throw new Error("GeoJSON filenames produce duplicate TypeScript exports");
    }

    await rm(outputDirectory, { force: true, recursive: true });
    await mkdir(outputDirectory, { recursive: true });
    await mkdir(path.dirname(manifestPath), { recursive: true });

    const manifestLines = [
        "// Generated by scripts/generate-geojson-assets.mjs. Do not edit.",
        "",
    ];

    for (const [exportName, sourceName] of assets) {
        const source = await readFile(path.join(sourceDirectory, sourceName));
        const extension = path.extname(sourceName);
        const basename = path.basename(sourceName, extension);
        const hash = createHash("sha256").update(source).digest("hex").slice(0, 12);
        const outputName = `${basename}-${hash}${extension}`;

        await writeFile(path.join(outputDirectory, outputName), source);
        manifestLines.push(
            `export const ${exportName} = "/geojson/generated/${outputName}";`,
        );
    }

    manifestLines.push("");
    await writeFile(manifestPath, manifestLines.join("\n"));
}

if (path.resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
    await generateGeoJsonAssets();
}
